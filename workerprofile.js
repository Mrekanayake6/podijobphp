/* =========================================================
   CHANGE WORKER PROFILE LANGUAGE
========================================================= */

function changeWorkerProfileLanguage(lang) {

    /*
       Only English / Sinhala
    */

    if (
        lang !== "en" &&
        lang !== "si"
    ) {

        lang = "en";

    }


    const translations =
        workerTranslations[lang];


    /* =====================================================
       WORKER PROFILE TRANSLATION
    ===================================================== */

    document
        .querySelectorAll("[data-i18n]")
        .forEach(function (element) {

            const key =
                element.getAttribute("data-i18n");


            if (
                translations[key] !== undefined
            ) {

                element.textContent =
                    translations[key];

            }

        });


    /* =====================================================
       SAVE LANGUAGE
    ===================================================== */

    localStorage.setItem(
        "podijobLanguage",
        lang
    );


    /* =====================================================
       HTML LANGUAGE
    ===================================================== */

    document.documentElement.lang =
        lang === "si"
            ? "si"
            : "en";


    /* =====================================================
       HEADER BUTTON ACTIVE STATE
    ===================================================== */

    const siBtn =
        document.getElementById("siBtn");

    const enBtn =
        document.getElementById("enBtn");


    if (siBtn) {

        siBtn.classList.toggle(
            "active",
            lang === "si"
        );

    }


    if (enBtn) {

        enBtn.classList.toggle(
            "active",
            lang === "en"
        );

    }

}


/* =========================================================
   MAIN LANGUAGE FUNCTION
   HEADER + WORKER PROFILE
========================================================= */

function changeLanguage(lang) {

    /*
       Validate language
    */

    if (
        lang !== "en" &&
        lang !== "si"
    ) {

        lang = "en";

    }


    /* =====================================================
       SAVE SELECTED LANGUAGE
    ===================================================== */

    localStorage.setItem(
        "podijobLanguage",
        lang
    );


    /* =====================================================
       HEADER TRANSLATION
       data-si / data-en
    ===================================================== */

    document
        .querySelectorAll(
            "[data-si][data-en]"
        )
        .forEach(function (element) {

            /*
               Worker profile elements
               data-i18n තියෙනවා නම්
               මෙතනින් skip කරන්න
            */

            if (
                element.hasAttribute(
                    "data-i18n"
                )
            ) {

                return;

            }


            /*
               INPUT
            */

            if (
                element.tagName === "INPUT"
            ) {

                element.placeholder =
                    lang === "si"
                        ? element.getAttribute(
                            "data-si"
                        )
                        : element.getAttribute(
                            "data-en"
                        );

                return;

            }


            /*
               TEXTAREA
            */

            if (
                element.tagName === "TEXTAREA"
            ) {

                element.placeholder =
                    lang === "si"
                        ? element.getAttribute(
                            "data-si"
                        )
                        : element.getAttribute(
                            "data-en"
                        );

                return;

            }


            /*
               NORMAL ELEMENT
            */

            element.textContent =
                lang === "si"
                    ? element.getAttribute(
                        "data-si"
                    )
                    : element.getAttribute(
                        "data-en"
                    );

        });


    /* =====================================================
       WORKER PROFILE
    ===================================================== */

    changeWorkerProfileLanguage(
        lang
    );


    /* =====================================================
       ACTIVE LANGUAGE BUTTON
    ===================================================== */

    const siBtn =
        document.getElementById("siBtn");

    const enBtn =
        document.getElementById("enBtn");


    if (siBtn) {

        siBtn.classList.toggle(
            "active",
            lang === "si"
        );

    }


    if (enBtn) {

        enBtn.classList.toggle(
            "active",
            lang === "en"
        );

    }


    /* =====================================================
       HTML LANG
    ===================================================== */

    document.documentElement.lang =
        lang === "si"
            ? "si"
            : "en";


    // ==========================================
    // UPDATE PLACEHOLDERS
    // ==========================================
    document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {

        const key = element.getAttribute("data-i18n-placeholder");

        if (translations[lang] && translations[lang][key]) {
            element.placeholder = translations[lang][key];
        }

    });

}


